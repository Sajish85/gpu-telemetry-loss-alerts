#!/usr/bin/env bash
# Runs every check and writes the raw, unedited output to TEST-OUTPUTS.md.
# Usage: capture-test-outputs.sh <promtool> <python with python-liquid + PyYAML>
set -u
PROMTOOL="$1"; PY="$2"
# Keep absolute paths out of TEST-OUTPUTS.md: put each tool's directory first on PATH
# (resolved before the cd below) and call the tools by bare name from here on.
for t in "$PROMTOOL" "$PY"; do
  case "$t" in */*) d="$(cd "$(dirname "$t")" && pwd)" || exit 1; PATH="$d:$PATH" ;; esac
done
export PATH
PROMTOOL="$(basename "$PROMTOOL")"; PY="$(basename "$PY")"
cd "$(dirname "$0")/.."
OUT=TEST-OUTPUTS.md
run() {  # run <title> <command...>
  { echo; echo "### $1"; echo; echo '```console'; echo "\$ ${*:2}"; } >> "$OUT"
  "${@:2}" >> "$OUT" 2>&1; rc=$?
  { echo "[exit status: $rc]"; echo '```'; } >> "$OUT"
}
{
  echo "# S1 test outputs (raw)"
  echo
  echo "Generated by \`scripts/capture-test-outputs.sh\` on $(date -u '+%Y-%m-%d %H:%M:%S UTC')."
  echo "Every block below is the unedited stdout+stderr of the command shown, followed by its exit status."
  echo "All series are synthetic. Nothing here ran against a live exporter, a Prometheus server or a GPU."
} > "$OUT"

run "Tool versions" bash -c "\"$PROMTOOL\" --version; \"$PY\" -c 'import importlib.metadata as m, sys; print(\"python\", sys.version.split()[0]); print(\"python-liquid\", m.version(\"python-liquid\")); print(\"PyYAML\", m.version(\"PyYAML\"))'; uname -sm"
run "Input checksums (SHA-256)" bash -c "shasum -a 256 original/* rules/* tests/* sources/* awesome-pr/rules-snippet.yml awesome-pr/nvidia-dcgm-exporter.test.yml"
run "Unit case count (test groups per file)" bash -c "for f in original/rules_test.yaml tests/rules_test.yaml tests/rules_test.legacy-4.8.yaml awesome-pr/nvidia-dcgm-exporter.test.yml; do printf '%s: ' \$f; grep -c -E -e '^ *- interval: 1m\$' -e '^- name: ' \$f; done"
run "Baseline: original files as copied from ~/krkn-gpu-work (unchanged)" bash -c "cd original && \"$PROMTOOL\" check rules rules.yaml && \"$PROMTOOL\" test rules rules_test.yaml"
run "Rule pack: make test (check, 6 unit cases on 4.9.0 names, 6 on 4.8 names, 4 mutants)" make test PROMTOOL="$PROMTOOL"
run "Cross-check: 4.8-named rules against 4.9-named series must FAIL (shows the port matters)" bash -c "d=\$(mktemp -d); mkdir -p \$d/rules \$d/tests; cp rules/dcgm-telemetry-loss.legacy-4.8.rules.yaml \$d/rules/dcgm-telemetry-loss.rules.yaml; cp tests/rules_test.yaml \$d/tests/; cd \$d/tests && \"$PROMTOOL\" test rules rules_test.yaml; rc=\$?; rm -rf \$d; echo \"expected non-zero, got \$rc\"; [ \$rc -ne 0 ]"
rm -rf awesome-pr/build
run "Awesome-list PR: render proposed rules with the repo's template (python-liquid emulation)" "$PY" -I scripts/render_awesome.py sources/awesome-rules-snapshot.yml sources/awesome-template-snapshot.yml awesome-pr/rules-snippet.yml awesome-pr/build
cp awesome-pr/nvidia-dcgm-exporter.test.yml awesome-pr/build/test/
run "Awesome-list PR: promtool check rules on the rendered exporter file" "$PROMTOOL" check rules awesome-pr/build/test/rules/nvidia-gpu/nvidia-dcgm-exporter.yml
run "Awesome-list PR: promtool test rules (proposed test/nvidia-dcgm-exporter.test.yml, 6 cases)" bash -c "cd awesome-pr/build/test && \"$PROMTOOL\" test rules nvidia-dcgm-exporter.test.yml"
run "Awesome-list PR: mutation check (4 mutants)" bash scripts/mutation-test-awesome.sh "$PROMTOOL" awesome-pr/build/test
echo "Wrote $OUT"
